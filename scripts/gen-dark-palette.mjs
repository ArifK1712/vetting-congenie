import fs from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const theme = fs.readFileSync(`${root}node_modules/tailwindcss/theme.css`, "utf8");
const vals = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (vals[m[1]] ??= {})[m[2]] = m[3].trim();
const flip = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };
const lines = [];
for (const [hue, steps] of Object.entries(vals)) {
  for (const [step, to] of Object.entries(flip)) if (steps[to]) lines.push(`  --color-${hue}-${step}: ${steps[to]};`);
}
const out = `/*
 * Dark theme. Generated by scripts/gen-dark-palette.mjs — do not edit by hand.
 * Tailwind's colour ramps are mirrored (50↔950, 100↔900 …, 500 stays) so the
 * tinted chips, pills and soft backgrounds used across the app turn into deep
 * tints with light text without touching any component.
 */
:root[data-theme="dark"] {
${lines.join("\n")}
}
`;
fs.writeFileSync(`${root}src/design/dark-palette.css`, out);
console.log(lines.length, "vars");
